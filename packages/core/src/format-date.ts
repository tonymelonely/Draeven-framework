const countryCodes = new Set<string>(Object.values(countries));
const locales = new Map<Country, string>();

/* The country chooses the order, separators, and digits. The calendar day stays UTC. */
export function formatDate(date: Date, country: Country): string {
  if (!(date instanceof Date) || Number.isNaN(date.getTime())) {
    throw new Error("[Draeven] A date is required.");
  }

  if (!countryCodes.has(country)) {
    throw new Error("[Draeven] Unknown country.");
  }

  return new Intl.DateTimeFormat(localeFor(country), {
    day: "2-digit",
    month: "2-digit",
    year: "numeric",
    timeZone: "UTC",
    calendar: "gregory",
  }).format(date);
}

function localeFor(country: Country): string {
  const cached = locales.get(country);

  if (cached) {
    return cached;
  }

  const locale = new Intl.Locale(`und-${country}`).maximize();
  const tag = `${locale.language}-${country}`;
  locales.set(country, tag);

  return tag;
}
